#!/usr/bin/env python3
"""Teste real do frontend. Requer playwright e Chromium; servidor já em execução.
Cria contas temporárias e as remove ao concluir. Use somente banco de testes.
"""
import os
import re
import uuid
from playwright.sync_api import sync_playwright, expect

base = os.getenv('UI_BASE_URL', 'http://127.0.0.1:8080').rstrip('/')
username = 'ui_' + uuid.uuid4().hex[:10]
email = username + '@example.test'
password = 'TesteLocal123!'
new_password = 'NovaSenhaLocal456!'
errors = []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path=os.getenv('CHROMIUM_PATH', '/usr/bin/chromium'), args=['--no-sandbox'])
    context = browser.new_context(permissions=['geolocation'], geolocation={'latitude': -23.56, 'longitude': -46.69})
    page = context.new_page()
    page.on('pageerror', lambda error: errors.append(str(error)))
    page.on('dialog', lambda dialog: dialog.accept())
    page.goto(base + '/avaliacoes.html')
    page.wait_for_url('**/Index.html')
    page.goto(base + '/Cadastro.html')
    expect(page.locator('[name=sobrenome]')).to_have_count(0)
    expect(page.locator('.campo [name=nome]')).to_have_count(1)
    expect(page.locator('.campo [name=username]')).to_have_count(1)
    assert page.locator('[name=nome]').evaluate('(e) => getComputedStyle(e.parentElement).borderRadius') == page.locator('[name=email]').evaluate('(e) => getComputedStyle(e.parentElement).borderRadius')
    page.screenshot(path='/tmp/urbaniza-cadastro.png', full_page=True)
    page.locator('[name=nome]').fill('Pessoa Teste UI')
    page.locator('[name=username]').fill(username)
    page.locator('[name=email]').fill(email)
    page.locator('[name=senha]').fill(password)
    page.locator('[name=confirmarSenha]').fill(password)
    page.get_by_role('button', name='Criar conta', exact=True).click()
    page.wait_for_url('**/inicio.html')
    expect(page.locator('#status')).to_contain_text('Ainda não há regiões avaliadas')
    expect(page.locator('#regioes-destaque .card-regiao')).to_have_count(0)
    bearer = {'Authorization': 'Bearer ' + page.evaluate("sessionStorage.getItem('urbaniza.token')")}
    highlight_reviews = []
    for region, score in [('pinheiros', 3), ('bairro-chacara-santo-antonio-santo-amaro', 5), ('moema', 1)]:
        response = context.request.post(base + '/api/avaliacoes', headers=bearer, data={'regiaoId': region, 'seguranca': score, 'mobilidade': score, 'iluminacao': score, 'comentario': 'Teste de destaque'})
        assert response.status == 201
        highlight_reviews.append(response.json()['id'])
        page.goto(base + '/inicio.html')
        cards = page.locator('#regioes-destaque .card-regiao')
        expect(cards).to_have_count(min(len(highlight_reviews), 2))
        if len(highlight_reviews) == 1:
            expect(cards.first).to_contain_text('Única região avaliada')
        else:
            expect(cards.first).to_contain_text('Maior média')
            expect(cards.first).to_contain_text('Chácara Santo Antônio')
            expect(cards.last).to_contain_text('Menor média')
            expect(cards.last).to_contain_text('Moema' if len(highlight_reviews) == 3 else 'Pinheiros')
    for review_id in highlight_reviews:
        assert context.request.delete(base + '/api/avaliacoes/' + str(review_id), headers=bearer).status == 204
    print('PASS: destaques sem avaliações, uma região e extremos de três regiões avaliadas')
    print('PASS: proteção de página, cadastro e início com dados da API')

    page.goto(base + '/avaliacoes.html?regiao=pinheiros')
    form = page.locator('#avaliacao-form')
    expect(form.locator('[name=regiaoId]')).to_have_value('pinheiros')
    expect(form.locator('[name=regiaoId] option')).to_have_count(614)
    page.get_by_role('searchbox', name='Pesquisar bairro', exact=True).fill('chacara santo antonio')
    expect(form.locator('[name=regiaoId]')).to_have_value('bairro-chacara-santo-antonio-santo-amaro')
    expect(form.locator('[name=regiaoId] option')).to_have_count(2)
    for key in ['seguranca', 'mobilidade', 'iluminacao']:
        form.locator(f'[name={key}]').select_option('5')
    form.locator('[name=comentario]').fill('Bairro local ' + username)
    form.get_by_role('button', name='Publicar avaliação').click()
    local_review = page.locator('#lista-avaliacoes article').filter(has_text='Bairro local ' + username)
    # O filtro da URL ainda é Pinheiros: selecione a lista completa para visualizar o bairro publicado.
    expect(page.locator('#status')).to_contain_text('Avaliação salva')
    page.locator('#filtro-regiao').select_option('')
    expect(local_review).to_have_count(1)
    local_review.get_by_role('button', name='Excluir', exact=True).click()
    expect(local_review).to_have_count(0)
    page.get_by_role('searchbox', name='Pesquisar bairro', exact=True).fill('bairro inexistente xyz')
    expect(page.locator('#resultado-busca-bairro')).to_contain_text('Nenhum bairro encontrado')
    page.get_by_role('searchbox', name='Pesquisar bairro', exact=True).fill('')
    form.locator('[name=regiaoId]').select_option('pinheiros')
    for key in ['seguranca', 'mobilidade', 'iluminacao']:
        form.locator(f'[name={key}]').select_option('4')
    form.locator('[name=comentario]').fill('Avaliação criada por ' + username)
    form.get_by_role('button', name='Publicar avaliação').click()
    own = page.locator('#lista-avaliacoes article').filter(has_text=username)
    expect(own).to_have_count(1)
    own.get_by_role('button', name='Editar', exact=True).click()
    form.locator('[name=comentario]').fill('Avaliação editada por ' + username)
    form.locator('[name=seguranca]').select_option('5')
    form.get_by_role('button', name='Salvar alterações').click()
    expect(own).to_contain_text('Avaliação editada')
    page.locator('#filtro-avaliacoes [name=minhas]').check()
    expect(page.locator('#lista-avaliacoes article')).to_have_count(1)
    print('PASS: POST, PUT, listagem e filtro de avaliações por Fetch')

    page.goto(base + '/mapa.html?regiao=pinheiros')
    expect(page.locator('#nome-regiao')).to_have_text('Pinheiros')
    expect(page.locator('#nota-regiao')).to_have_text('4,3')
    expect(page.locator('.leaflet-overlay-pane path').first).to_be_attached(timeout=10000)
    expect(page.locator('.leaflet-overlay-pane path')).to_have_count(96)
    expect(page.locator('.area-mapa-wrapper > #detalhe-regiao')).to_be_visible()
    expect(page.locator('#estrelas-regiao .estrela.ativa')).to_have_count(4)
    expect(page.locator('.nome-bairro-mapa')).to_have_count(96)
    expect(page.locator('.leaflet-tile-pane img').first).to_have_attribute('src', re.compile(r'https://tile\.openstreetmap\.org/'))
    polygon = page.locator('.leaflet-overlay-pane path').first
    polygon.dispatch_event('mouseover')
    expect(polygon).to_have_attribute('fill-opacity', '0.18')
    polygon.dispatch_event('mouseout')
    expect(polygon).to_have_attribute('fill-opacity', '0.05')
    page.locator('#input-busca-regiao').fill('chacara santo antonio')
    expect(page.locator('#nome-regiao')).to_have_text('Chácara Santo Antônio')
    expect(page.locator('#zona-regiao')).to_contain_text('Santo Amaro')
    expect(page.locator('#avaliar-regiao')).to_have_attribute('href', 'avaliacoes.html?regiao=bairro-chacara-santo-antonio-santo-amaro')
    page.locator('#input-busca-regiao').fill('Moema')
    expect(page.locator('#lista-regioes')).to_have_count(0)
    expect(page.get_by_role('heading', name='Regiões disponíveis', exact=True)).to_have_count(0)
    expect(page.locator('.nome-bairro-mapa')).to_have_count(1)
    expect(page.locator('#nome-regiao')).to_have_text('Moema')
    page.get_by_role('button', name='Segurança', exact=True).click()
    expect(page.locator('#total-avaliacoes')).to_contain_text('Segurança')
    page.get_by_role('button', name='Segurança', exact=True).click()
    expect(page.locator('[data-categoria=geral]')).to_have_attribute('aria-pressed', 'true')
    page.get_by_role('button', name='Minha localização', exact=True).click()
    expect(page.locator('#status')).to_contain_text('Localização encontrada')
    page.get_by_role('button', name='Aproximar', exact=True).click()
    page.get_by_role('button', name='Afastar', exact=True).click()
    page.screenshot(path='/tmp/urbaniza-mapa.png', full_page=True)
    page.set_viewport_size({'width': 375, 'height': 812})
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth'), 'Mapa com rolagem horizontal em mobile'
    page.screenshot(path='/tmp/urbaniza-mapa-mobile.png', full_page=True)
    page.set_viewport_size({'width': 1280, 'height': 720})
    print('PASS: mapa original com ruas configuradas, 96 distritos, hover, marcadores nomeados, card, estrelas, médias reais, filtros, zoom, geolocalização e mobile')

    page.goto(base + '/perfil.html')
    expect(page.locator('#perfil-nome')).to_have_text('Pessoa Teste UI')
    expect(page.locator('.card-usuario .avatar')).to_be_visible()
    expect(page.get_by_role('heading', name='Suporte', exact=True)).to_be_visible()
    expect(page.locator('#perfil-form')).not_to_be_visible()
    page.screenshot(path='/tmp/urbaniza-perfil.png', full_page=True)
    page.get_by_role('link', name='Editar meu perfil', exact=True).click()
    form = page.locator('#perfil-form')
    expect(form.locator('[name=username]')).to_have_value(username)
    form.locator('[name=nome]').fill('Nome Atualizado')
    form.locator('[name=username]').fill(username + '_novo')
    form.locator('[name=localidade]').fill('São Paulo • SP')
    form.get_by_role('button', name='Salvar perfil').click()
    expect(page.locator('#perfil-nome')).to_have_text('Nome Atualizado')
    page.get_by_role('button', name='Sair da conta', exact=True).click()
    page.wait_for_url('**/Index.html')
    page.locator('[name=identificador]').fill(username + '_novo')
    page.locator('[name=senha]').fill(password)
    page.get_by_role('button', name='Mostrar senha', exact=True).click()
    expect(page.locator('[name=senha]')).to_have_attribute('type', 'text')
    page.get_by_role('button', name='Entrar', exact=True).click()
    page.wait_for_url('**/inicio.html')
    page.goto(base + '/perfil.html')
    page.get_by_role('button', name='Sair da conta', exact=True).click()
    page.wait_for_url('**/Index.html')
    print('PASS: PUT do perfil, logout, novo username e alternância de senha')

    page.goto(base + '/RecuperarSenha.html')
    page.locator('[name=email]').fill(email)
    page.get_by_role('button', name='Enviar código', exact=True).click()
    page.wait_for_url('**/VerificarCodigo.html')
    code = re.search(r'\b\d{6}\b', page.locator('.aviso-local').inner_text()).group()
    page.locator('[name=codigo]').fill(code)
    page.get_by_role('button', name='Verificar código', exact=True).click()
    page.wait_for_url('**/NovaSenha.html')
    page.locator('[name=senha]').fill(new_password)
    page.locator('[name=confirmarSenha]').fill(new_password)
    page.get_by_role('button', name='Salvar nova senha', exact=True).click()
    page.wait_for_url('**/Index.html')
    page.locator('[name=identificador]').fill(email)
    page.locator('[name=senha]').fill(password)
    page.get_by_role('button', name='Entrar', exact=True).click()
    expect(page.locator('.mensagem')).to_contain_text('incorretos')
    page.locator('[name=senha]').fill(new_password)
    page.get_by_role('button', name='Entrar', exact=True).click()
    page.wait_for_url('**/inicio.html')
    print('PASS: recuperação local completa, rejeição da senha antiga e login por email')

    page.goto(base + '/avaliacoes.html')
    page.locator('#filtro-avaliacoes [name=minhas]').check()
    own = page.locator('#lista-avaliacoes article').filter(has_text=username)
    expect(own).to_have_count(1)
    own.get_by_role('button', name='Excluir', exact=True).click()
    expect(own).to_have_count(0)
    page.goto(base + '/perfil.html')
    page.get_by_role('button', name='Excluir conta', exact=True).click()
    page.locator('#excluir-conta-form [name=senha]').fill(new_password)
    page.get_by_role('button', name='Sim, excluir', exact=True).click()
    page.wait_for_url('**/Index.html')
    print('PASS: DELETE da avaliação e exclusão de conta com confirmação de senha')

    admin_username = os.getenv('UI_ADMIN_USERNAME')
    admin_password = os.getenv('UI_ADMIN_PASSWORD')
    if admin_username and admin_password:
        # Conta descartável separada para consultar, promover, rebaixar e remover.
        other_name = 'mod_' + uuid.uuid4().hex[:10]
        result = context.request.post(base + '/api/auth/cadastro', data={'nome': 'Usuário Moderação', 'username': other_name, 'email': other_name + '@example.test', 'senha': password})
        assert result.status == 201
        other = result.json()
        result = context.request.post(base + '/api/avaliacoes', headers={'Authorization': 'Bearer ' + other['token']}, data={'regiaoId': 'se', 'seguranca': 3, 'mobilidade': 3, 'iluminacao': 3, 'comentario': 'Moderação ' + other_name})
        assert result.status == 201
        page.locator('[name=identificador]').fill(admin_username)
        page.locator('[name=senha]').fill(admin_password)
        page.get_by_role('button', name='Entrar', exact=True).click()
        page.wait_for_url('**/inicio.html')
        page.goto(base + '/perfil.html')
        page.get_by_role('link', name='Administrar usuários').click()
        page.locator('#buscar-usuario [name=username]').fill(other_name)
        page.locator('#buscar-usuario').get_by_role('button', name='Buscar', exact=True).click()
        card = page.locator('#lista-usuarios article').filter(has_text=other_name)
        expect(page.locator('#lista-usuarios article')).to_have_count(1)
        card.get_by_role('button', name='Tornar administrador').click()
        expect(card).to_contain_text('Papel: ADMIN')
        card.get_by_role('button', name='Tornar usuário').click()
        expect(card).to_contain_text('Papel: USER')
        page.goto(base + '/avaliacoes.html')
        review = page.locator('#lista-avaliacoes article').filter(has_text=other_name)
        expect(review).to_have_count(1)
        review.get_by_role('button', name='Excluir', exact=True).click()
        expect(review).to_have_count(0)
        page.goto(base + '/admin.html')
        page.locator('#lista-usuarios article').filter(has_text=other_name).get_by_role('button', name='Excluir usuário').click()
        expect(page.locator('#lista-usuarios article').filter(has_text=other_name)).to_have_count(0)
        print('PASS: painel admin, GET por username, RBAC, alteração de papel, moderação e exclusão')
    else:
        print('SKIP: painel admin (defina UI_ADMIN_USERNAME e UI_ADMIN_PASSWORD num banco de testes)')
    assert not errors, errors
    browser.close()
print('PASS: nenhum erro JavaScript não tratado no navegador')
